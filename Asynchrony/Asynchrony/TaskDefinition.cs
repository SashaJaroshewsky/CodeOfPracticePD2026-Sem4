namespace Asynchrony
{
    // Task - це клас, який представляє асинхронну операцію.
    // Він дозволяє виконувати код асинхронно, не блокуючи потік виконання.
    // Task може бути використаний для виконання будь-якої операції, яка може зайняти деякий час,
    // наприклад, завантаження даних з мережі, читання файлу або виконання складних обчислень.

    // Дуже простими словами
    // Task - це обіцянка, що якесь завдання буде виконано в майбутньому.

    internal class TaskDefinition
    {
        Task Task; // Це поле представляє собою об'єкт Task, який може бути використаний для виконання асинхронної операції.

        // Task має багато метовів і властивостей, які дозволяють керувати асинхронними операціями, наприклад:

        // Методи на екземплярі Task:
        // - Start(): Запускає виконання Task.
        // - Wait(): Блокує потік, доки Task не завершиться.
        // - ContinueWith(Action<Task> continuationAction): Додає продовження, яке буде виконано після завершення Task.

        // Властивості на екземплярі Task:
        // - IsCompleted: Показує, чи завершився Task.
        // - IsFaulted: Показує, чи завершився Task з помилкою.
        // - Result: Отримує результат виконання Task (для Task<T>).
        // - Exception: Отримує виключення, якщо Task завершився з помилкою.
        // - Status: Показує поточний статус Task (наприклад, RanToCompletion, Faulted, Canceled).
        // - Id: Унікальний ідентифікатор Task.
        // - CreationOptions: Показує параметри створення Task (наприклад, LongRunning, PreferFairness).
        // - AsyncState: Отримує об'єкт, який був переданий при створенні Task для зберігання стану.

        // Task також має статичні методи, які дозволяють створювати і керувати Task, наприклад:
        // - Run(Action action): Створює і запускає Task, який виконує вказану дію. 
        // - WhenAll(params Task[] tasks): Створює Task, який завершиться, коли всі вказані Task завершаться.
        // - WhenAny(params Task[] tasks): Створює Task, який завершиться, коли будь-який з вказаних Task завершиться.
        // - Delay(int millisecondsDelay): Створює Task, який завершиться після вказаної затримки.
        // - FromResult(TResult result): Створює завершений Task<T>, який містить вказаний результат.
        // - FromException(Exception exception): Створює завершений Task, який містить вказане виключення.
        // - FromCanceled(CancellationToken cancellationToken): Створює завершений Task, який був скасований.
        // - RunSynchronously(): Запускає Task синхронно на поточному потоці.
        // - StartNew(Action action): Створює і запускає Task, який виконує вказану дію (альтернатива Run).
        // - Factory.StartNew(Action action): Створює і запускає Task, який виконує вказану дію (ще одна альтернатива Run).


        // Коли методи потрібно робити асинхронними?

        // Метод чекає щось ззовні? (мережа, файл, БД) → async
        // Метод викликає інший async метод? → async

        // Метод рахує / фільтрує / мапить? → синхронний

        // Типова архітектура
        // Controller → Service → Repository → DB 
        // DB - це зовнішній ресурс, тому всі методи, які працюють з БД, повинні бути асинхронними.
        // Отже всі методи в Repository повинні бути асинхронними, а всі методи в Service і Controller, які викликають ці методи, також повинні бути асинхронними.

    }
}
