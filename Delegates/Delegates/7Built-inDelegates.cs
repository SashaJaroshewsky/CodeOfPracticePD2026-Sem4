namespace Delegates
{
    internal class BuiltInDelegates
    {
        // В C# існують вбудовані делегати, які надають зручні способи роботи з делегатами без необхідності оголошувати власні типи делегатів.
        // Найпоширенішими вбудованими делегатами є Action, Func і Predicate.

        // 1. Action: Використовується для делегатів, які не повертають значення. Він може приймати від 0 до 16 параметрів.
        // Наприклад:
        private Action<string>? _printMessage;
        
        // 2. Func: Використовується для делегатів, які повертають значення. Він може приймати від 0 до 16 параметрів, а останній параметр визначає тип повернення.
        // Наприклад:
        private Func<int, int, int>? _add;
        
        // 3. Predicate: Використовується для делегатів, які повертають булеве значення (true або false). Він приймає один параметр і визначає умову.
        // Наприклад:
        private Predicate<int>? _isEven;


        public void Example()
        {
            // Ініціалізація вбудованих делегатів
            _printMessage = ShowMessage;
            _add = AddNumbers;
            _isEven = IsEvenNumber;

            // Виклик вбудованих делегатів
            _printMessage("Hello, World!"); // Виведе: Hello, World!
            int sum = _add(10, 5); // sum буде 15
            bool checkEven = _isEven(10); // checkEven буде true
        }
        private void ShowMessage(string message)
        {
            Console.WriteLine(message);
        }

        private int AddNumbers(int a, int b)
        {
            return a + b;
        }

        private bool IsEvenNumber(int number)
        {
            return number % 2 == 0;
        }

        // Використання вбудованих делегатів робить код більш читабельним і зручним для розробників.
        // Вони широко використовуються в різних сценаріях, таких як обробка подій, LINQ-запити та асинхронне програмування.

        //Існують також інші вбудовані делегати

        //Наприклад:

        // - Comparison<T>: Використовується для порівняння двох об'єктів одного типу.
        // - Converter<TInput, TOutput>: Використовується для перетворення об'єкта одного типу в об'єкт іншого типу.
        // - EventHandler: Використовується для обробки подій.
        // - EventHandler<TEventArgs>: Використовується для обробки подій з додатковими аргументами події.

        // Ці вбудовані делегати допомагають спростити розробку і зробити код більш ефективним.

        //Коли використовувати вбудовані делегати замість власних?
        // - Простота: Якщо ваш делегат має просту сигнатуру, використання вбудованих делегатів робить код більш читабельним.
        // - Універсальність: Вбудовані делегати охоплюють більшість поширених сценаріїв використання делегатів.
        // - Зменшення коду: Використання вбудованих делегатів зменшує кількість коду, який потрібно написати і підтримувати.
        // - Стандартизація: Використання вбудованих делегатів сприяє стандартизації коду і полегшує його розуміння іншими розробниками.
        // Однак, якщо ваш делегат має складну сигнатуру або специфічні вимоги, може бути доцільно оголосити власний тип делегата.
        // Або якщо ви хочете надати більш описову назву для делегата, що покращить розуміння його призначення.
        
    }
}
