namespace Delegates
{
    internal class LambdaExpressions
    {
        // Лямбда-вирази в C# є компактним способом визначення анонімних функцій або методів.

        // Вони дозволяють створювати делегати або дерева виразів більш стислим і читабельним способом.

        // Лямбда-вирази використовують оператор "=>" для розділення списку параметрів і тіла виразу.
        // Ось кілька ключових моментів про лямбда-вирази:

        // 1. Синтаксис: Лямбда-вирази мають наступний синтаксис:
        // (параметри) => вираз  виразні (expression-bodied)
        // або
        // (параметри) => { блок коду }  блокові (statement-bodied)

        // 2. Використання з делегатами: Лямбда-вирази часто використовуються для створення екземплярів делегатів, таких як Func, Action і Predicate.
        // 3. Захоплення змінних: Лямбда-вирази можуть захоплювати змінні з зовнішнього контексту, що дозволяє їм використовувати ці змінні всередині свого тіла.
        // 4. Використання в LINQ: Лямбда-вирази широко використовуються в LINQ для визначення умов фільтрації, проекції та інших операцій над колекціями.

        // Ось приклад використання лямбда-виразів для створення делегатів:

        public void Example()
        {
            // Використання лямбда-виразів для створення делегатів

            // Лямбда-вираз для додавання двох чисел
            // Повне пояснення: Func<int, int, int> - це делегат, який приймає два параметри типу int і повертає значення типу int.
            // Лямбда-вираз (x, y) => x + y визначає функцію, яка приймає два параметри x і y і повертає їх суму.
            Func<int, int, int> add = (x, y) => x + y;
            int sum = add(10, 5); // sum буде 15

            Action<string> printMessage = message => Console.WriteLine(message);
            printMessage("Hello, World!"); // Виведе: Hello, World!

            Predicate<int> isEven = number => number % 2 == 0;
            bool checkEven = isEven(10); // checkEven буде true

            // Захоплення змінних
            int factor = 2;
            Func<int, int> multiply = x => x * factor;
            int product = multiply(10); // product буде 20
            // У цьому прикладі лямбда-вираз захоплює змінну factor з зовнішнього контексту.
            // Це дозволяє використовувати значення factor всередині тіла лямбда-виразу.
            // Для зміни значення factor після створення лямбда-виразу, нове значення буде використовуватися при наступних викликах multiply.
            // Для чого це потрібно?
            // Захоплення змінних дозволяє створювати більш гнучкі і динамічні функції,
            // які можуть адаптуватися до змін у зовнішньому контексті.
            
            factor = 3;
            int newProduct = multiply(10); // newProduct буде 30
            // Тепер multiply використовує оновлене значення factor.
            // Життєвий цикл захоплених змінних пов'язаний з життєвим циклом лямбда-виразу.
            // Захоплені змінні зберігаються в замиканні (closure), яке підтримує їх значення навіть після виходу з області видимості.
            

            // Використання лямбда-виразів в LINQ
            // Припустимо, у нас є список чисел, і ми хочемо відфільтрувати парні числа.
            // Ми можемо використовувати лямбда-вирази разом з LINQ для досягнення цього.
            List<int> numbers = new List<int> { 1, 2, 3, 4, 5, 6 };
            var evenNumbers = numbers.Where(n => n % 2 == 0).ToList();
            // Детальне пояснення:
            // У цьому прикладі ми використовуємо метод розширення Where з LINQ, щоб відфільтрувати парні числа зі списку numbers.
            // Лямбда-вираз n => n % 2 == 0 визначає умову фільтрації, де n представляє кожен елемент у списку.
            // Результатом є новий список evenNumbers, який містить лише парні числа: [2, 4, 6].
            // Where приймає делегат Func<int, bool>, який визначає умову для фільтрації елементів.
            // Чому не Predicate<int>?
            // Хоча Predicate<int> також можна використовувати для визначення умови, LINQ використовує Func<int, bool> для більшої гнучкості.
            // Func дозволяє повертати будь-який тип, тоді як Predicate обмежений булевим значенням.
            // Використання Func<int, bool> дозволяє створювати більш складні умови фільтрації, якщо це необхідно.
        }
    }
}
