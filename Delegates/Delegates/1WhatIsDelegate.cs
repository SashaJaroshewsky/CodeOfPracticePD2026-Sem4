namespace Delegates
{
    internal class WhatIsDelegate
    {
        // Делегати — це ключова концепція в C#.
        // Вони дозволяють передавати методи як параметри,
        // зберігати їх у змінних і викликати пізніше.

        // Простими словами
        // Делегат — це тип, який може зберігати посилання на метод(и) з певною сигнатурою.

        // Він дозволяє передавати методи як параметри, зберігати їх у змінних і викликати їх динамічно.

        // Ось кілька ключових моментів про делегати:
        // 1. Оголошення делегата: Делегат оголошується за допомогою ключового слова "delegate", за яким слідує тип повернення і список параметрів.
        // 2. Використання делегата: Після оголошення делегата можна створювати змінні цього типу і присвоювати їм методи, які відповідають сигнатурі делегата.
        // 3. Виклик делегата: Делегат можна викликати так само, як і звичайний метод, передаючи необхідні аргументи.
        // 4. Мультикаст делегати: Делегати можуть посилатися на кілька методів одночасно, що дозволяє викликати всі ці методи послідовно.

        // Ось приклад оголошення делегата, який приймає два цілі числа і повертає ціле число:
        public delegate int MathOperation(int a, int b);

        private int Add(int x, int y)
        {
            return x + y;
        }

        private int Subtract(int x, int y)
        {
            return x - y;
        }

        public void Example()
        {
            // Створення екземпляра делегата і присвоєння йому методу Add
            MathOperation operation = Add;

            // Виклик делегата
            int result = operation(5, 3);
            Console.WriteLine($"Result: {result}"); // Виведе: Result: 8

            // Зміна методу, на який посилається делегат
            operation = Subtract;

            // Виклик делегата
            result = operation(5, 3);
            Console.WriteLine($"Result: {result}"); // Виведе: Result: 2

            // Чи обов'язково зберігати результат виклику делегата в змінній?
            // Ні, ви можете викликати делегат безпосередньо без збереження результату:
            operation(12, 7); // Виклик делегата без збереження результату
        }

    }
}
