using System.IO;
namespace FileIO
{
    // Уявіть, що файл на диску — це величезний резервуар з водою. Вам потрібно перемістити цю воду в інше місце (у вашу програму).
    // Ви не можете перенести весь резервуар миттєво, тому ви прокладаєте трубу.

    // Stream (Потік) — це і є ця "труба". Це абстракція, яка дозволяє передавати дані як послідовність байтів один за одним.
    // Потік може бути спрямований у різні напрямки: з файлу на диск, з мережі, з пам'яті тощо. Ви можете читати з потока або записувати в нього.

    // Чому ми використовуємо потоки, а не вантажимо все одразу?
    // 1. Економія пам'яті: Якщо файл важить 10 ГБ, а у вас лише 8 ГБ оперативної пам'яті, ви не зможете прочитати його цілком.
    //    Потік дозволяє читати файл частинами (наприклад, по 4 КБ).
    // 2. Ефективність: Читання великих файлів може зайняти багато часу. Потоки дозволяють почати обробку даних, не чекаючи, поки весь файл буде завантажений.
    // 3. Гнучкість: Потоки можуть бути використані для різних джерел даних, не обмежуючись лише файлами. Ви можете читати з мережі, з пам'яті або навіть створювати власні потоки.
    // 4. Універсальність: Програмі байдуже, звідки йдуть байти — з файлу на диску, з мережевого запиту чи з мікрофона. Якщо це Stream, ви працюєте з ним однаково.
    internal class StreamExplanation
    {
        // У .NET базовим класом для всіх потоків є абстрактний клас System.IO.Stream. Він визначає "правила гри" для всіх типів потоків.
        private Stream _stream;

        // Кожен потік зазвичай підтримує три основні дії:
        //  Read (Читання): Перенесення даних із потоку в структуру даних (наприклад, масив байтів).
        //  Write(Запис) : Перенесення даних із вашої структури в потік.
        //  Seek(Пошук/Позиціонування): Можливість перейти до конкретного місця в потоці(не всі потоки це підтримують, наприклад, у мережевому потоці не можна "відмотати" назад).

        // Основні властивості:
        //  CanRead, CanWrite, CanSeek — булеві значення, що показують, які операції доступні.
        //  Length — довжина потоку(кількість байтів).
        //  Position — де ми зараз знаходимося в цій "трубі".

        // Види Stream у .NET
        // Оскільки Stream — це абстрактний "батько", у нього є багато спеціалізованих "дітей":

        // FileStream	    Читання та запис файлів на диску.                      
        // MemoryStream     Робота з даними в оперативній пам'яті (як з файлом).
        // NetworkStream    Передача даних по мережі.
        // GZipStream       Стиснення даних "на льоту".

        // Важливий момент: IDisposable
        // Потоки використовують некеровані ресурси (файлові дескриптори, мережеві підключення).
        // Якщо ви відкриєте файл і не закриєте потік, операційна система може заблокувати цей файл для інших програм.

        // Тому потоки завжди потрібно закривати. У C# для цього використовується конструкція using, яка автоматично викликає Dispose() після завершення роботи з потоком:

        public void ExampleUsing()
        {
            using (FileStream fs = File.OpenRead("test.txt"))
            {
                // Працюємо з файлом...
            } // Тут потік закриється автоматично, навіть якщо виникне помилка
        }
    }
}

