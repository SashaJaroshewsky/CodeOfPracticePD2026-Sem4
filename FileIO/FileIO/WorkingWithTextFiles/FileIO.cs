namespace FileIO.WorkingWithTextFiles
{
    // File — це статичний клас з простору імен System.IO, який надає зручні методи для роботи з файлами.
    // Він дозволяє легко створювати, читати, записувати та видаляти файли без необхідності вручну керувати потоками.
    // Під капотом використовує FileStream для виконання операцій з файлами, але він абстрагує ці деталі, надаючи простий інтерфейс для розробників.

    // Клас File найкраще підходить для невеликих файлів(конфігурації, налаштування, короткі замітки), де швидкість написання коду важливіша за тонке налаштування потоків.
    // Клас File — це насправді "фабрика" для потоків. Більшість його методів просто створюють FileStream всередині себе, роблять роботу і закривають його.
    // Клас File статичний і не підтримує створення екземплярів, тому всі його методи є статичними. Це означає, що ви можете викликати їх безпосередньо через ім'я класу, наприклад, File.WriteAllText() або File.ReadAllText().


    internal class FileIO
    {
        // Методи класу File:
        // File.WriteAllText(string path, string contents) — записує вказаний текст у файл. Якщо файл існує, він буде перезаписаний.
        // File.ReadAllText(string path) — читає весь текст з файлу і повертає його як рядок. Якщо файл не існує, буде викинута помилка.
        // File.ReadLines(string path) — читає текст з файлу построчно і повертає IEnumerable<string>, що дозволяє ефективно обробляти великі файли без завантаження їх повністю в пам'ять.
        // File.AppendAllText(string path, string contents) — додає вказаний текст до кінця файлу. Якщо файл не існує, він буде створений.
        // File.Delete(string path) — видаляє файл за вказаним шляхом. Якщо файл не існує, буде викинута помилка.
        // File.Exists(string path) — перевіряє, чи існує файл за вказаним шляхом, і повертає true або false.
        // File.Copy(string sourceFileName, string destFileName) — копіює файл з одного місця в інше. Якщо цільовий файл існує, буде викинута помилка.
        // File.Move(string sourceFileName, string destFileName) — переміщує файл з одного місця в інше. Якщо цільовий файл існує, буде викинута помилка.
        // File.Create(string path) — створює новий файл за вказаним шляхом і повертає FileStream для запису. Якщо файл існує, він буде перезаписаний.

        // File.ReadAllLines(string path) — читає текст з файлу построчно і повертає масив рядків. Це зручно для обробки текстових файлів, де кожен рядок має окреме значення або запис.
        // File.WriteAllLines(string path, IEnumerable<string> contents) — записує колекцію рядків у файл, кожен рядок буде записаний на новому рядку. Якщо файл існує, він буде перезаписаний. Це зручно для створення текстових файлів з кількома рядками.
        // File.AppendAllLines(string path, IEnumerable<string> contents) — додає колекцію рядків до кінця файлу, кожен рядок буде записаний на новому рядку. Якщо файл не існує, він буде створений. Це зручно для додавання записів до текстового файлу без перезапису існуючих даних.



        // Приклади використання методів класу File:
        public void FileClassExamples()
        {
            // Записуємо текст у файл
            File.WriteAllText("example.txt", "Записуємо текст у файл");
            // Читаємо текст з файлу
            string content = File.ReadAllText("example.txt");
            Console.WriteLine(content);
            // Додаємо текст до файлу
            File.AppendAllText("example.txt", "\nWelcome to C# programming!");

            // Читаємо текст з файлу по рядку
            IEnumerable<string> lines = File.ReadLines("example.txt");
            foreach (string line in lines)
            {
                Console.WriteLine(line);
            }

            // Видаляємо файл
            File.Delete("example.txt");
            // Перевіряємо, чи існує файл
            bool exists = File.Exists("example.txt");
            Console.WriteLine($"Файл існує: {exists}");

            // Копіюємо файл
            File.WriteAllText("source.txt", "Це вихідний файл для копіювання.");
            File.Copy("source.txt", "destination.txt");
            // Переміщуємо файл
            File.Move("destination.txt", "moved.txt");
            // Створюємо новий файл
            File.Create("newfile.txt").Close(); // Створюємо новий файл і закриваємо його, щоб звільнити ресурс
            
        }

        // File працює не лише з текстовими файлами, але і з будь-якими іншими типами файлів, оскільки він фактично є обгорткою над FileStream.
        // Це означає, що ви можете використовувати його для роботи з бінарними файлами, зображеннями, відео та іншими типами даних,
        // просто використовуючи відповідні методи для читання та запису байтів замість тексту.

        // Важливо пам'ятати, що при роботі з великими файлами або коли потрібен більш контрольований доступ до файлу, краще використовувати потоки (FileStream, StreamReader, StreamWriter) замість класу File, щоб уникнути проблем з продуктивністю та пам'яттю.

        // Методи для роботи з не текстовими файлами:
        // File.ReadAllBytes(string path) — читає весь вміст файлу і повертає його як масив байтів. Це зручно для роботи з бінарними файлами, такими як зображення, аудіо або відео.
        // File.WriteAllBytes(string path, byte[] bytes) — записує масив байтів у файл. Якщо файл існує, він буде перезаписаний. Це зручно для створення або оновлення бінарних файлів.
        // File.AppendAllBytes(string path, byte[] bytes) — додає масив байтів до кінця файлу. Якщо файл не існує, він буде створений. Це зручно для додавання даних до бінарного файлу без перезапису існуючих даних.
        


    }
}
