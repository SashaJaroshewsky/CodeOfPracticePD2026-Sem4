using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Events
{
    internal class SubscribeAndUnsubscribe
    {
        // Підписка на подію здійснюється за допомогою оператора +=, який додає метод-обробник до списку викликів події.
        // Відписка від події здійснюється за допомогою оператора -=, який видаляє метод-обробник зі списку викликів події.
        public class Button
        {
            // Делегат для події кліку кнопки
            public delegate void ClickEventHandler(object sender);
            // Подія кліку кнопки
            public event ClickEventHandler Clicked;
            // Метод для імітації кліку кнопки
            public void OnClick()
            {
                Console.WriteLine("Button clicked!");
                // Виклик події
                Clicked?.Invoke(this);
            }
        }
        public class ButtonHandler
        {
            // Метод-обробник події кліку кнопки
            public void HandleButtonClick(object sender)
            {
                Console.WriteLine("Button click event handled.");
            }
        }

        public void Example()
        {
            // Створення кнопки
            Button button = new Button();
            // Створення обробника кнопки
            ButtonHandler handler = new ButtonHandler();
            // Підписка на подію кліку кнопки
            button.Clicked += handler.HandleButtonClick;
            // Імітація кліку кнопки
            button.OnClick();
            // Відписка від події кліку кнопки
            button.Clicked -= handler.HandleButtonClick;
            // Імітація кліку кнопки після відписки
            button.OnClick();
        }

        // Чому обов’язково відписуватися від подій?
        // Відписка від подій є важливою практикою з кількох причин:
        // Запобігання витокам пам'яті: Якщо об'єкт підписується на подію, але не відписується від неї, він може залишатися в пам'яті навіть після того, як він більше не потрібен.
        // Це може призвести до витоків пам'яті, оскільки збирач сміття не зможе звільнити пам'ять, зайняту цим об'єктом.
        // Контроль над поведінкою програми: Відписка від подій дозволяє контролювати, які об'єкти реагують на певні події в певний момент часу.
        // Якщо об'єкт більше не потребує реагування на подію, відписка допомагає уникнути небажаних викликів методів.
        // Покращення продуктивності: Якщо багато об'єктів підписані на одну подію, це може вплинути на продуктивність програми.
        // Відписка від непотрібних подій допомагає зменшити кількість викликів методів і покращити загальну продуктивність.
        // Запобігання помилкам: Якщо об'єкт залишається підписаним на подію після того, як він був видалений або більше не існує,
        // це може призвести до виклику методів на неіснуючих об'єктах, що викликає помилки в програмі.
        // Відписка від подій є важливою практикою для забезпечення стабільності, продуктивності та правильного управління пам'яттю в програмах, які використовують події.

        




    }
}
